test('routes block present and current: one block per gk workflow (none in gk-selftest), right after the gk-project END line', () => {
  const files = scripts()
  assert.ok(files.includes('gk-selftest.js'))
  for (const f of files) {
    const wf = wfOf(f)
    const src = readFileSync(join(workflowsDir, f), 'utf8')
    const blk = blockOf(src)
    if (!stagesOf(wf).length) {
      assert.equal(blk.count, 0, `${f}: no routes block (no stages in routes.json)`)
      continue
    }
    assert.equal(blk.count, 1, `${f}: exactly one routes block`)
    assert.ok(blk.end > blk.begin, `${f}: the block is closed`)
    assert.ok(blk.lines[blk.begin - 1].includes(PROJECT_END), `${f}: the block starts on the line after the gk-project END line`)
    assert.equal(Number(BEGIN.exec(blk.lines[blk.begin])[1]), routes.version, `${f}: the block names routes.json's version`)
    assert.ok(blk.text.includes(helperSource.trimEnd()), `${f}: the helper is the template, verbatim`)
    // The block runs on its own, and its data is this workflow's slice of routes.json.
    const { ROUTES } = evalBlock(blk.text)
    assert.equal(ROUTES.version, routes.version)
    assert.deepEqual(Object.keys(ROUTES.stages), stagesOf(wf), `${f}: the block holds this workflow's stages, in order`)
    for (const k of stagesOf(wf)) assert.deepEqual(ROUTES.stages[k], routes.stages[k], `${f}: stage ${k}`)
    for (const [name, t] of Object.entries(ROUTES.tiers)) {
      const r = routes.tiers[name]
      assert.ok(r, `${f}: tier ${name} is in routes.json`)
      assert.deepEqual([t.model, t.effort], [r.model, r.effort], `${f}: tier ${name}`)
      assert.deepEqual(t.cap, [routes.models[r.model].rank, routes.efforts.indexOf(r.effort) + 1], `${f}: tier ${name} capability`)
    }
    // Every tier any of its stages can name is in the block.
    for (const k of stagesOf(wf)) {
      const s = routes.stages[k]
      const named = [s.tier, ...Object.values(s.byClass || {}), ...Object.values(s.when || {}),
        ...(typeof s.noFable === 'object' ? Object.values(s.noFable) : [s.noFable])]
      for (const t of named) if (t && t !== 'byClass' && t !== 'none') assert.ok(ROUTES.tiers[t], `${f}: ${k} names tier ${t}`)
    }
  }
})

test('meta.phases labels: every phase is mapped to a stage in routes.json phases, and a labelled phase names its base tier\'s model', () => {
  for (const f of scripts()) {
    const wf = wfOf(f)
    if (!stagesOf(wf).length) continue
    const src = readFileSync(join(workflowsDir, f), 'utf8')
    const head = src.slice(0, markerAt(src).at)
    const meta = new Function(`return (${head.slice('export const meta = '.length)})`)()
    const map = routes.phases[wf]
    assert.ok(map, `${f}: routes.json phases has an entry`)
    assert.deepEqual(Object.keys(map).sort(), meta.phases.map((p) => p.title).sort(), `${f}: every phase that runs an agent is mapped`)
    for (const p of meta.phases) {
      const s = routes.stages[map[p.title]]
      assert.ok(s && map[p.title].startsWith(`${wf}.`), `${f}: phase ${p.title} maps to a stage of this workflow`)
      if (!('model' in p)) continue
      const base = s.tier === 'byClass' ? s.byClass.judgement : s.tier
      assert.equal(p.model, routes.tiers[base].model, `${f}: phase ${p.title} model label`)
    }
  }
})

