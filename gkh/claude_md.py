"""The policy block in ~/.claude/CLAUDE.md, and the marker-block text helpers that the shell rc
block (gkh.shell) shares.

A marker block runs from a line that is a begin marker to the next line that is an end marker
(a marker line may carry stray surrounding whitespace). Text outside the blocks is the
machine's own and is kept byte for byte, a byte-order mark at the start of the file included:
a marker on line 1 is still a marker after an editor adds one. All functions here are pure text
in, text out.
"""
from __future__ import annotations

import re
from typing import Callable

BEGIN_RE = re.compile(r"<!-- gk-harness:begin v\S+ -->")
END_MARKER = "<!-- gk-harness:end -->"
GENERATED_LINE = ("<!-- generated by gk-harness: edit policy.md in the gk-harness repo, "
                  "then run install -->")
OLD_POLICY_FIRST_LINE = "# Model orchestration policy"
LABEL = "CLAUDE.md"
BOM = "\ufeff"


class BlockError(ValueError):
    """The markers in a file do not pair up, so the installer cannot tell its block from the
    machine's own text. The message names the file and the line."""


def begin_marker(version: str) -> str:
    return "<!-- gk-harness:begin v%s -->" % version


def is_begin(line: str) -> bool:
    return BEGIN_RE.fullmatch(line.strip()) is not None


def is_end(line: str) -> bool:
    return line.strip() == END_MARKER


# --- generic marker blocks ------------------------------------------------------------------

def newline_of(text: str) -> str:
    """The file's newline: "\\r\\n" when it has any, else "\\n"."""
    return "\r\n" if "\r\n" in text else "\n"


def bom_of(text: str) -> str:
    """The byte-order mark the text starts with, or ""."""
    return BOM if text.startswith(BOM) else ""


def _lines(text: str):
    """(start, end, line) for each line; end includes the line's "\\n". A byte-order mark at
    the start is not part of line 1."""
    pos = len(bom_of(text))
    while pos < len(text):
        nl = text.find("\n", pos)
        end = len(text) if nl < 0 else nl + 1
        yield pos, end, text[pos:end]
        pos = end


def marker_spans(text: str, begin: Callable[[str], bool], end: Callable[[str], bool],
                 label: str) -> list:
    """[(start, stop)] character spans of the blocks, each from the start of its begin line to
    the end of its end line. Raises BlockError on a begin inside a block, an end outside one, or
    a block that never ends."""
    spans, open_at, open_line = [], None, 0
    for number, (start, stop, line) in enumerate(_lines(text), 1):
        if begin(line):
            if open_at is not None:
                raise BlockError("%s: a gk-harness begin marker on line %d comes before the end of "
                                 "the block opened on line %d; fix the markers by hand"
                                 % (label, number, open_line))
            open_at, open_line = start, number
        elif end(line):
            if open_at is None:
                raise BlockError("%s: a gk-harness end marker on line %d has no begin marker; fix "
                                 "the markers by hand" % (label, number))
            spans.append((open_at, stop))
            open_at = None
    if open_at is not None:
        raise BlockError("%s: the gk-harness block opened on line %d has no end marker; fix the "
                         "markers by hand" % (label, open_line))
    return spans


def _cut(text: str, spans: list) -> str:
    """text without the spans. A block that ran to the end of the text takes with it the blank
    line apply_block put before it: the one empty line ("\\r\\n" or "\\n") right after a line
    end. apply_block writes that line in the file's newline, which in a file with mixed
    newlines need not match the line end before it ("a\\r\\nb\\n" gets "\\r\\n")."""
    out, pos = [], 0
    for start, stop in spans:
        out.append(text[pos:start])
        pos = stop
    tail = text[pos:]
    if spans and tail == "":
        before = "".join(out)
        for blank in ("\r\n", "\n"):
            if before.endswith("\n" + blank):
                out = [before[:-len(blank)]]
                break
    return "".join(out) + tail


def apply_block(existing: str | None, block: str, begin: Callable[[str], bool],
                end: Callable[[str], bool], label: str) -> tuple:
    """(new_text, mode) with block (written with "\\n") in place, in the file's own newline.

    mode is "created" (no file), "unchanged", "updated" (the first block replaced in place and
    any others removed) or "appended" (after the text and one blank line).
    """
    if existing is None:
        return block, "created"
    nl = newline_of(existing)
    blk = block.replace("\n", nl)
    spans = marker_spans(existing, begin, end, label)
    if spans:
        first_start, first_stop = spans[0]
        new = existing[:first_start] + blk + _cut(existing[first_stop:],
                                                  [(s - first_stop, e - first_stop)
                                                   for s, e in spans[1:]])
        return new, ("unchanged" if new == existing else "updated")
    bom = bom_of(existing)
    if existing == bom:
        return bom + blk, "appended"
    return existing + ("" if existing.endswith("\n") else nl) + nl + blk, "appended"


def strip_blocks(text: str, begin: Callable[[str], bool], end: Callable[[str], bool],
                 label: str) -> str:
    """text without its blocks (the inverse of apply_block's "appended"); a byte-order mark at
    the start stays."""
    return _cut(text, marker_spans(text, begin, end, label))


# --- the policy block -----------------------------------------------------------------------

def render_block(policy: str, version: str) -> str:
    """The block: begin marker, the generated line, the policy, the end marker, each line ending
    in "\\n". Raises BlockError when the policy itself holds a marker line."""
    body = policy.replace("\r\n", "\n").rstrip("\n").split("\n")
    for number, line in enumerate(body, 1):
        if is_begin(line) or is_end(line):
            raise BlockError("policy.md: line %d is a gk-harness marker" % number)
    return "\n".join([begin_marker(version), GENERATED_LINE] + body + [END_MARKER]) + "\n"


def is_old_policy(text: str) -> bool:
    """True when the first line is exactly the old policy's title and the file has no block."""
    first = text.lstrip(BOM).split("\n", 1)[0].rstrip("\r")
    if first != OLD_POLICY_FIRST_LINE:
        return False
    try:
        return not marker_spans(text, is_begin, is_end, LABEL)
    except BlockError:
        return False


def has_block(text: str) -> bool:
    return bool(marker_spans(text, is_begin, is_end, LABEL))


def apply(existing: str | None, block: str) -> tuple:
    """(new_text, mode) for CLAUDE.md. As apply_block, plus "replaced_old_policy": a file with
    no block whose first line is the old policy's title is the old policy, so the block replaces
    it whole (the caller backs it up first)."""
    if existing is not None and is_old_policy(existing):
        return block.replace("\n", newline_of(existing)), "replaced_old_policy"
    return apply_block(existing, block, is_begin, is_end, LABEL)


def strip(text: str) -> str:
    """text without its blocks. A file apply created or replaced strips to "", or to a lone
    byte-order mark when an editor has added one since."""
    return strip_blocks(text, is_begin, is_end, LABEL)
