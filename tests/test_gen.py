from __future__ import annotations

import json
import os
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, str(ROOT))

from gkh import cli, gen  # noqa: E402
from gkh import routes as rt  # noqa: E402


class GenTests(unittest.TestCase):
    def test_generated_agents_equal_committed(self):
        self.assertEqual(gen.stale(ROOT), [])

    def test_stale_lists_a_hand_edit(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            shutil.copy(str(ROOT / "routes.json"), str(root / "routes.json"))
            shutil.copytree(str(ROOT / "agents"), str(root / "agents"))
            with open(str(root / "agents" / "worker-opus.md"), "a", encoding="utf-8", newline="") as f:
                f.write("hand edit\n")
            self.assertEqual(gen.stale(root), ["agents/worker-opus.md"])
            self.assertEqual(gen.write(root), ["agents/worker-opus.md"])
            self.assertEqual(gen.stale(root), [])
            self.assertEqual(gen.write(root), [])

    def test_gen_check_exit_code(self):
        self.assertEqual(cli.main(["gen", "--check"]), 0)

    # --- the workflow routes block -----------------------------------------------------------

    def _tree(self, tmp: str) -> Path:
        root = Path(tmp)
        shutil.copy(str(ROOT / "routes.json"), str(root / "routes.json"))
        shutil.copytree(str(ROOT / "agents"), str(root / "agents"))
        shutil.copytree(str(ROOT / "workflows"), str(root / "workflows"))
        return root

    def test_routes_block_shape(self):
        routes = rt.load(ROOT / "routes.json")
        block = gen.render_routes_block(routes, "gk-build")
        lines = block.split("\n")
        self.assertEqual(lines[0], "// <gk-routes v2> generated by gkh gen from routes.json v%d; do not edit"
                         % routes["version"])
        self.assertTrue(block.endswith("// </gk-routes>\n"))
        helper = (ROOT / "gkh" / "templates" / "routes-helper.js").read_text(encoding="utf-8")
        self.assertIn(helper.rstrip("\n"), block)
        self.assertIn('"gk-build.implement"', block)
        self.assertNotIn('"gk-review.judge"', block)
        self.assertEqual(gen.render_routes_block(routes, "gk-selftest"), "")

    def test_routes_block_tiers_cover_floors(self):
        routes = rt.load(ROOT / "routes.json")
        data = gen.routes_data(routes, "gk-review")
        # authorFloor: the author can be any tier, so every tier is in the block.
        self.assertEqual(list(data["tiers"]), list(routes["tiers"]))
        diagnose = gen.routes_data(routes, "gk-diagnose")
        # Only what its stages name: the base tiers, noFable and the apex tier.
        self.assertEqual(list(diagnose["tiers"]), ["opus-high", "opus-xhigh", "fable-medium", "fable-high"])
        self.assertEqual(data["tiers"]["opus-high"], {"model": "opus", "effort": "high", "cap": [3, 3]})
        build = gen.routes_data(routes, "gk-build")
        # atLeast: every tier the implementer can run on.
        for t in ("sonnet-medium", "opus-medium", "fable-medium", "opus-high", "opus-xhigh"):
            self.assertIn(t, build["tiers"])

    def test_routes_block_follows_project_end_and_is_rewritten_in_place(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = self._tree(tmp)
            self.assertEqual(gen.stale(root), [])
            path = root / "workflows" / "gk-review.js"
            text = path.read_text(encoding="utf-8")
            self.assertIn("gk-project block: END =================\n// <gk-routes v2>", text)
            # A hand edit inside the block is stale; gen puts it back.
            path.write_text(text.replace('"tier": "haiku-medium"', '"tier": "opus-high"', 1), encoding="utf-8")
            self.assertEqual(gen.stale(root), ["workflows/gk-review.js"])
            self.assertEqual(gen.write(root), ["workflows/gk-review.js"])
            self.assertEqual(path.read_text(encoding="utf-8"), text)
            # A missing block is stale; gen inserts it after the END line.
            begin = text.index("// <gk-routes v2>")
            end = text.index("// </gk-routes>\n") + len("// </gk-routes>\n")
            path.write_text(text[:begin] + text[end:], encoding="utf-8")
            self.assertEqual(gen.stale(root), ["workflows/gk-review.js"])
            gen.write(root)
            self.assertEqual(path.read_text(encoding="utf-8"), text)
            # gk-selftest gets no block.
            self.assertNotIn("<gk-routes", (root / "workflows" / "gk-selftest.js").read_text(encoding="utf-8"))

    def test_phase_labels_follow_routes(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = self._tree(tmp)
            routes = json.loads((root / "routes.json").read_text(encoding="utf-8"))
            routes["stages"]["gk-diagnose.hypothesise"]["tier"] = "sonnet-medium"
            (root / "routes.json").write_text(json.dumps(routes, indent=2), encoding="utf-8")
            self.assertIn("workflows/gk-diagnose.js", gen.write(root))
            text = (root / "workflows" / "gk-diagnose.js").read_text(encoding="utf-8")
            self.assertRegex(text, r"\{ title: 'Hypothesise', detail: '[^\n]*', model: 'sonnet' \},")
            self.assertRegex(text, r"\{ title: 'Test', detail: '[^\n]*', model: 'opus' \},")

    def test_phase_label_byclass_uses_judgement_and_unlabelled_phases_stay(self):
        text = (ROOT / "workflows" / "gk-build.js").read_text(encoding="utf-8")
        self.assertRegex(text, r"\{ title: 'Implement', detail: '[^\n]*', model: 'opus' \},")
        judge = [l for l in text.split("\n") if l.startswith("    { title: 'Judge'")]
        self.assertEqual(len(judge), 1)
        self.assertNotIn("model:", judge[0])

    def test_script_without_project_end_is_an_error(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = self._tree(tmp)
            path = root / "workflows" / "gk-research.js"
            path.write_text(path.read_text(encoding="utf-8").replace("gk-project block: END", "gk-project block: FIN"),
                            encoding="utf-8")
            with self.assertRaises(rt.RoutesError):
                gen.outputs(root)


    # --- the policy's class table ------------------------------------------------------------

    def test_policy_table_rows_and_columns(self):
        routes = rt.load(ROOT / "routes.json")
        table = gen.render_policy_table(routes)
        lines = table.splitlines()
        self.assertEqual(lines[0], gen.TABLE_BEGIN)
        self.assertEqual(lines[-1], gen.TABLE_END)
        self.assertEqual(lines[1], "| Class | Examples | Who | Tier | Check | Evidence |")
        rows = [ln for ln in lines[3:] if ln.startswith("| ")]
        self.assertEqual([r.split(" | ")[0][2:] for r in rows], list(routes["classes"]))
        self.assertIn("| feature | %s | worker | `opus-medium`, then `opus-high` | %s | guide |"
                      % (routes["classes"]["feature"]["examples"], routes["classes"]["feature"]["check"]), lines)
        self.assertTrue(any(r.startswith("| legal-doc |") and "seat, at least `opus-medium`" in r
                            for r in rows))
        self.assertIn("Ladder: " + " → ".join("`%s`" % t for t in routes["ladder"]) + ".", lines)

    def test_policy_table_hand_edit_is_stale_and_rewritten(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = self._tree(tmp)
            shutil.copy(str(ROOT / "policy.md"), str(root / "policy.md"))
            self.assertEqual(gen.stale(root), [])
            path = root / "policy.md"
            text = path.read_text(encoding="utf-8")
            path.write_text(text.replace("| search |", "| searching |"), encoding="utf-8")
            self.assertEqual(gen.stale(root), ["policy.md"])
            self.assertEqual(gen.write(root), ["policy.md"])
            self.assertEqual(path.read_text(encoding="utf-8"), text)

    def test_policy_without_table_markers_is_an_error(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = self._tree(tmp)
            (root / "policy.md").write_text("# Model orchestration policy\n", encoding="utf-8")
            with self.assertRaises(rt.RoutesError):
                gen.outputs(root)


if __name__ == "__main__":
    unittest.main()
