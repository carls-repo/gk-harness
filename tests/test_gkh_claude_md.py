from __future__ import annotations

import os
import sys
import unittest
from pathlib import Path

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import gkh  # noqa: E402
from gkh import claude_md as cm  # noqa: E402

POLICY = "# Model orchestration policy\n\nRoute work to the cheapest tier.\n"
OLD = "# Model orchestration policy\n\nThe main session runs Fable 5.1.\n"
NOTES = "# This machine\n\n- the dev stack runs under systemd\n"


def block(version="1.0.0", policy=POLICY):
    return cm.render_block(policy, version)


class RenderTests(unittest.TestCase):
    def test_constants(self):
        self.assertEqual(cm.begin_marker("1.0.0"), "<!-- gk-harness:begin v1.0.0 -->")
        self.assertEqual(cm.END_MARKER, "<!-- gk-harness:end -->")
        self.assertEqual(cm.GENERATED_LINE, "<!-- generated by gk-harness: edit policy.md in the "
                                            "gk-harness repo, then run install -->")
        self.assertEqual(cm.OLD_POLICY_FIRST_LINE, "# Model orchestration policy")

    def test_block_layout(self):
        self.assertEqual(block(), "<!-- gk-harness:begin v1.0.0 -->\n" + cm.GENERATED_LINE + "\n"
                         + POLICY + "<!-- gk-harness:end -->\n")

    def test_policy_newlines_are_normalised(self):
        self.assertEqual(cm.render_block("a\r\nb\r\n\r\n\r\n", "1.0.0"), cm.render_block("a\nb", "1.0.0"))

    def test_policy_holding_a_marker_is_refused(self):
        for bad in ("x\n<!-- gk-harness:end -->\n", "<!-- gk-harness:begin v2 -->\n"):
            with self.assertRaises(cm.BlockError):
                cm.render_block(bad, "1.0.0")

    def test_the_real_policy_renders(self):
        text = (Path(ROOT) / "policy.md").read_text(encoding="utf-8")
        b = cm.render_block(text, gkh.VERSION)
        self.assertEqual(len(cm.marker_spans(b, cm.is_begin, cm.is_end, "CLAUDE.md")), 1)
        self.assertEqual(cm.strip(b), "")


class ApplyTests(unittest.TestCase):
    def test_absent_file(self):
        self.assertEqual(cm.apply(None, block()), (block(), "created"))

    def test_empty_file(self):
        self.assertEqual(cm.apply("", block()), (block(), "appended"))

    def test_notes_are_kept_and_the_block_appended(self):
        new, mode = cm.apply(NOTES, block())
        self.assertEqual((new, mode), (NOTES + "\n" + block(), "appended"))
        new2, mode2 = cm.apply("notes", block())
        self.assertEqual((new2, mode2), ("notes\n\n" + block(), "appended"))

    def test_old_policy_is_replaced_whole(self):
        self.assertEqual(cm.apply(OLD, block()), (block(), "replaced_old_policy"))
        crlf = OLD.replace("\n", "\r\n")
        self.assertEqual(cm.apply(crlf, block()), (block().replace("\n", "\r\n"), "replaced_old_policy"))

    def test_first_line_must_match_exactly(self):
        for text in ("# Model orchestration policy (draft)\n", " # Model orchestration policy\n",
                     "# model orchestration policy\n", "\n# Model orchestration policy\n",
                     "# Model orchestration policy \n"):
            new, mode = cm.apply(text, block())
            self.assertEqual(mode, "appended", repr(text))
            self.assertTrue(new.startswith(text))

    def test_existing_block_is_updated_in_place(self):
        installed, _ = cm.apply(NOTES, block("1.0.0"))
        installed += "\n# Later notes\n"
        new, mode = cm.apply(installed, block("1.1.0", "new policy\n"))
        self.assertEqual(mode, "updated")
        self.assertEqual(new, NOTES + "\n" + block("1.1.0", "new policy\n") + "\n# Later notes\n")
        self.assertEqual(cm.apply(new, block("1.1.0", "new policy\n")), (new, "unchanged"))

    def test_a_file_with_a_block_is_never_old_policy(self):
        text = block("0.9.0", OLD) + "\nmy notes\n"
        new, mode = cm.apply(text, block())
        self.assertEqual((new, mode), (block() + "\nmy notes\n", "updated"))
        self.assertFalse(cm.is_old_policy(text))

    def test_a_second_block_is_removed(self):
        text = block("0.9.0") + "\nmid\n\n" + block("0.8.0")
        new, mode = cm.apply(text, block())
        self.assertEqual((new, mode), (block() + "\nmid\n", "updated"))

    def test_crlf_file_gets_crlf_block(self):
        notes = NOTES.replace("\n", "\r\n")
        new, _ = cm.apply(notes, block())
        self.assertEqual(new, notes + "\r\n" + block().replace("\n", "\r\n"))
        self.assertEqual(cm.strip(new), notes)

    def test_unbalanced_markers_raise_naming_the_file(self):
        begin = "<!-- gk-harness:begin v1.0.0 -->\n"
        end = "<!-- gk-harness:end -->\n"
        for text in (NOTES + begin + "policy\n", NOTES + end, begin + begin + end):
            with self.subTest(text=text):
                with self.assertRaises(cm.BlockError) as ctx:
                    cm.apply(text, block())
                self.assertIn("CLAUDE.md", str(ctx.exception))
                with self.assertRaises(cm.BlockError):
                    cm.strip(text)

    def test_markers_with_stray_spaces_are_recognised(self):
        text = "  <!-- gk-harness:begin v1.0.0 -->  \nold\n<!-- gk-harness:end -->\t\n"
        self.assertEqual(cm.apply(text, block()), (block(), "updated"))

    def test_marker_mentioned_inside_a_line_is_not_a_marker(self):
        text = "Notes: the block starts at `<!-- gk-harness:begin v1 -->`.\n"
        self.assertEqual(cm.apply(text, block()), (text + "\n" + block(), "appended"))


class StripTests(unittest.TestCase):
    def test_round_trips(self):
        for start in (NOTES, NOTES + "\n", "x\n\n\n"):
            with self.subTest(start=start):
                new, _ = cm.apply(start, block())
                self.assertEqual(cm.strip(new), start)

    def test_unterminated_notes_gain_only_a_newline(self):
        new, _ = cm.apply("notes", block())
        self.assertEqual(cm.strip(new), "notes\n")

    def test_created_and_replaced_strip_to_empty(self):
        self.assertEqual(cm.strip(cm.apply(None, block())[0]), "")
        self.assertEqual(cm.strip(cm.apply(OLD, block())[0]), "")

    def test_text_after_the_block_is_kept(self):
        new, _ = cm.apply(NOTES, block())
        self.assertEqual(cm.strip(new + "added later\n"), NOTES + "\nadded later\n")

    def test_no_block_is_unchanged(self):
        self.assertEqual(cm.strip(NOTES), NOTES)
        self.assertFalse(cm.has_block(NOTES))
        self.assertTrue(cm.has_block(cm.apply(NOTES, block())[0]))

    def test_end_marker_without_final_newline(self):
        text = NOTES + "\n" + block().rstrip("\n")
        self.assertEqual(cm.strip(text), NOTES)


class OldPolicyTests(unittest.TestCase):
    def test_detection(self):
        self.assertTrue(cm.is_old_policy(OLD))
        self.assertTrue(cm.is_old_policy("# Model orchestration policy"))
        self.assertTrue(cm.is_old_policy("﻿# Model orchestration policy\r\nx"))
        self.assertFalse(cm.is_old_policy(NOTES))
        self.assertFalse(cm.is_old_policy(""))


if __name__ == "__main__":
    unittest.main()
