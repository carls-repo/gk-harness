"""Generates agents/*.md, and the routes block of every workflows/gk-*.js, from routes.json (the
single source of truth).

Three kinds of agent file: one per tier (worker-<tier>), one per retired name (the target
tier's model, effort and body, under a "Retired name: use worker-<tier>." description), and one
per extra agent in "agents" (Explore), which may carry a tools line.

Workflow scripts cannot read files or import modules, so each gk workflow with stages in
routes.json carries a generated routes block, directly after its gk-project block's END line:
the workflow's slice of routes.json (ROUTES) and the routing helper copied from
gkh/templates/routes-helper.js. gen also writes each mapped phase's `model` label in the
script's meta (routes.json "phases"), from the stage's base tier (byClass: the judgement
class); a phase with no `model` key is left without one.

policy.md carries the class table between TABLE_BEGIN and TABLE_END, written by
render_policy_table; the rest of policy.md is hand-written and kept byte for byte."""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import routes as rt

TEMPLATES = Path(__file__).resolve().parent / "templates"
HELPER = TEMPLATES / "routes-helper.js"
BLOCK_BEGIN = "// <gk-routes v2> generated by gkh gen from routes.json v%s; do not edit"
BLOCK_END = "// </gk-routes>"
BLOCK = re.compile(r"^// <gk-routes v\d+>[^\n]*\n.*?^// </gk-routes>\n", re.S | re.M)
PROJECT_END = "gk-project block: END"
PHASE_LINE = re.compile(r"^(\s*\{ title: '([^'\\]*)'.*\bmodel: ')([a-z0-9-]+)(' \},?)$")
PHASE_TITLE = re.compile(r"^\s*\{ title: '([^'\\]*)'")
TABLE_BEGIN = "<!-- gk-routes:table -->"
TABLE_END = "<!-- /gk-routes:table -->"
TABLE = re.compile(r"^<!-- gk-routes:table -->\n.*?^<!-- /gk-routes:table -->\n", re.S | re.M)
FINISHING_HEADING = "# Finishing work"
FINISHING_EFFORTS = ("low", "medium")
# A YAML plain scalar may not hold ": " or " #", nor start with an indicator character.
_PLAIN_UNSAFE = re.compile(r": | #|^[-?:,\[\]{}#&*!|>'\"%@`]|:$")


def _scalar(text: str) -> str:
    """text as a YAML scalar: plain when that is safe, else a JSON (YAML double-quoted) string."""
    return json.dumps(text, ensure_ascii=False) if _PLAIN_UNSAFE.search(text) else text


def _render(name: str, description: str, model: str, effort: str, body: str, tools=None) -> str:
    head = ("---\nname: %s\ndescription: %s\nmodel: %s\neffort: %s\n"
            % (name, _scalar(description), model, effort))
    if tools:
        head += "tools: %s\n" % tools
    return head + "---\n" + body


def tier_body(routes: dict, tier_name: str) -> str:
    """The tier's body, with the finishing-work text appended for low and medium effort."""
    t = rt.tier(routes, tier_name)
    body = t["body"]
    finishing = routes.get("finishingWork")
    if finishing and t["effort"] in FINISHING_EFFORTS:
        body = "%s\n\n%s\n\n%s\n" % (body.rstrip("\n"), FINISHING_HEADING, finishing)
    return body


def render_agent(routes: dict, tier_name: str) -> str:
    t = rt.tier(routes, tier_name)
    return _render(t["agent"], t["description"], t["model"], t["effort"], tier_body(routes, tier_name))


def render_retired(routes: dict, name: str) -> str:
    target = routes["retired"][name]
    t = rt.tier(routes, target)
    description = "Retired name: use %s. %s" % (t["agent"], t["description"])
    return _render(name, description, t["model"], t["effort"], tier_body(routes, target))


def render_extra(routes: dict, name: str) -> str:
    a = routes["agents"][name]
    t = rt.tier(routes, a["tier"])
    return _render(name, a["description"], t["model"], t["effort"], a["body"], a.get("tools"))


# --- the workflow routes block ------------------------------------------------------------

def _helper() -> str:
    return HELPER.read_text(encoding="utf-8")


def _helper_const(name: str) -> str:
    """A tier the helper names (ROUTE_FLOOR, ROUTE_APEX), read from the template itself."""
    m = re.search(r"^const %s = '([^']+)'$" % name, _helper(), re.M)
    if not m:
        raise rt.RoutesError("%s: no const %s" % (HELPER, name))
    return m.group(1)


def workflow_stages(routes: dict, workflow: str) -> list:
    return [k for k in routes.get("stages") or {} if k.split(".", 1)[0] == workflow]


def _tiers_used(routes: dict, stages: list) -> list:
    """Every tier routeOf can reach or compare against for these stages, in routes.json order."""
    floor, apex = _helper_const("ROUTE_FLOOR"), _helper_const("ROUTE_APEX")
    used = set()
    for key in stages:
        s = routes["stages"][key]
        if s.get("tier") == rt.BY_CLASS:
            used.update((s.get(rt.BY_CLASS) or {}).values())
        else:
            used.add(s.get("tier"))
        used.update((s.get("when") or {}).values())
        nf = s.get("noFable")
        used.update(nf.values() if isinstance(nf, dict) else [nf])
        if s.get("apex"):
            used.add(apex)
        if s.get("atLeast"):
            # The implementer is a tier of a stage this one judges, before any dial (ruling R4).
            used.add(floor)
            for judged in (routes.get("judges") or {}).get(key) or []:
                used.update(rt.stage_variants(routes, judged).values())
        if s.get("authorFloor"):
            # The author can be any tier; one the block does not hold is logged as unknown.
            used.add(floor)
            used.update(routes["tiers"])
    used.discard(None)
    used.discard(rt.NO_FABLE_NONE)
    return [t for t in routes["tiers"] if t in used]


def routes_data(routes: dict, workflow: str) -> dict:
    """The ROUTES object of the workflow's block: {version, tiers, stages}. A tier carries its
    model alias, effort and cap = [model rank, effort position], the capability order."""
    stages = workflow_stages(routes, workflow)
    tiers = {}
    for name in _tiers_used(routes, stages):
        t = rt.tier(routes, name)
        tiers[name] = {"model": t["model"], "effort": t["effort"],
                       "cap": list(rt.capability(routes, name))}
    return {"version": routes["version"], "tiers": tiers,
            "stages": {k: routes["stages"][k] for k in stages}}


def render_routes_block(routes: dict, workflow: str) -> str:
    """The workflow's routes block, from the begin marker to the end marker; "" when routes.json
    has no stage for it."""
    if not workflow_stages(routes, workflow):
        return ""
    data = routes_data(routes, workflow)

    def dump(value) -> str:
        return json.dumps(value, ensure_ascii=False)

    def section(name: str) -> str:
        rows = ["    %s: %s" % (dump(k), dump(v)) for k, v in data[name].items()]
        return "  %s: {\n%s\n  }" % (dump(name), ",\n".join(rows))

    data = "{\n  \"version\": %s,\n%s,\n%s\n}" % (dump(data["version"]), section("tiers"), section("stages"))
    helper = _helper()
    if not helper.endswith("\n"):
        helper += "\n"
    return "%s\nconst ROUTES = %s\n%s%s\n" % (BLOCK_BEGIN % routes["version"], data, helper, BLOCK_END)


def _base_model(routes: dict, stage: str) -> str:
    s = routes["stages"][stage]
    base = (s.get(rt.BY_CLASS) or {}).get("judgement") if s.get("tier") == rt.BY_CLASS else s.get("tier")
    return rt.tier(routes, base)["model"]


def _label_phases(routes: dict, workflow: str, text: str, rel: str) -> str:
    """text with each mapped meta.phases entry's model label set from its stage's base tier."""
    mapping = (routes.get("phases") or {}).get(workflow) or {}
    if not mapping:
        return text
    close = text.find("\n}\n")
    if not text.startswith("export const meta = {") or close < 0:
        raise rt.RoutesError("%s: meta is not the first statement" % rel)
    lines = text[:close + 1].split("\n")
    seen = set()
    for i, line in enumerate(lines):
        title = PHASE_TITLE.match(line)
        if not title or title.group(1) not in mapping:
            continue
        seen.add(title.group(1))
        m = PHASE_LINE.match(line)
        if m:
            lines[i] = m.group(1) + _base_model(routes, mapping[m.group(2)]) + m.group(4)
    missing = sorted(set(mapping) - seen)
    if missing:
        raise rt.RoutesError("%s: routes.json phases names titles not in meta.phases: %s"
                             % (rel, ", ".join(missing)))
    return "\n".join(lines) + text[close + 1:]


def render_script(routes: dict, workflow: str, text: str, rel: str = "") -> str:
    """text with its routes block regenerated (or removed) and its phase labels rewritten."""
    rel = rel or "workflows/%s.js" % workflow
    text = BLOCK.sub("", text)
    block = render_routes_block(routes, workflow)
    if block:
        at = text.find(PROJECT_END)
        if at < 0:
            raise rt.RoutesError("%s: no gk-project block END line to put the routes block after" % rel)
        eol = text.find("\n", at)
        if eol < 0:
            raise rt.RoutesError("%s: the gk-project block END line is the last line" % rel)
        text = text[:eol + 1] + block + text[eol + 1:]
    return _label_phases(routes, workflow, text, rel)


# --- the policy's class table -------------------------------------------------------------

def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _class_tier(c: dict) -> str:
    tier = c.get("tier")
    out = tier if tier == rt.SEAT_TIER else "`%s`" % tier
    if c.get("next"):
        out += ", then `%s`" % c["next"]
    if c.get("floor"):
        out += ", at least `%s`" % c["floor"]
    return out


def render_policy_table(routes: dict) -> str:
    """The policy's class table, from TABLE_BEGIN to TABLE_END (each line ending in "\n"): one
    row per class in routes.json order (class, examples, who, tier with its next or floor tier,
    check, evidence), then the escalation ladder."""
    evidence = routes.get("evidence") or {}
    rows = [TABLE_BEGIN, "| Class | Examples | Who | Tier | Check | Evidence |",
            "|---|---|---|---|---|---|"]
    for name, c in (routes.get("classes") or {}).items():
        rows.append("| %s | %s | %s | %s | %s | %s |" % (
            name, _cell(c.get("examples", "")), c.get("who", ""), _class_tier(c),
            _cell(c.get("check", "")), _cell(evidence.get(name, ""))))
    ladder = routes.get("ladder") or []
    if ladder:
        rows += ["", "Ladder: " + " → ".join("`%s`" % t for t in ladder) + "."]
    rows.append(TABLE_END)
    return "\n".join(rows) + "\n"


def render_policy(routes: dict, text: str) -> str:
    """policy.md text with its class table regenerated. Raises RoutesError without the markers."""
    if len(TABLE.findall(text)) != 1:
        raise rt.RoutesError("policy.md: needs one class table between %s and %s lines"
                             % (TABLE_BEGIN, TABLE_END))
    table = render_policy_table(routes)
    return TABLE.sub(lambda _m: table, text)


def outputs(root: Path) -> dict:
    """Repo-relative path -> the text that file should hold."""
    root = Path(root)
    routes = rt.load(root / "routes.json")
    out = {"agents/%s.md" % rt.tier(routes, name)["agent"]: render_agent(routes, name)
           for name in routes["tiers"]}
    for name in routes.get("retired") or {}:
        out["agents/%s.md" % name] = render_retired(routes, name)
    for name in routes.get("agents") or {}:
        out["agents/%s.md" % name] = render_extra(routes, name)
    policy = _current(root / "policy.md")
    if policy is not None:
        out["policy.md"] = render_policy(routes, policy)
    folder = root / "workflows"
    for script in sorted(folder.glob("gk-*.js")) if folder.is_dir() else ():
        rel = "workflows/%s" % script.name
        current = _current(script)
        if current is not None:
            out[rel] = render_script(routes, script.name[:-len(".js")], current, rel)
    return out


def _current(path: Path):
    try:
        with open(str(path), encoding="utf-8", newline="") as f:
            return f.read()
    except OSError:
        return None


def stale(root: Path) -> list:
    root = Path(root)
    return [rel for rel, text in outputs(root).items() if _current(root / rel) != text]


def write(root: Path) -> list:
    root = Path(root)
    written = []
    for rel, text in outputs(root).items():
        if _current(root / rel) != text:
            target = root / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            with open(str(target), "w", encoding="utf-8", newline="") as f:
                f.write(text)
            written.append(rel)
    return written
