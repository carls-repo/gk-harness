// The generated routes block (Task 8): every gk workflow but gk-selftest carries one block,
// written by `gkh gen` from routes.json right after the gk-project block's END line, and the
// routing helper inside it (routeOf, runStage, routingResult, DIALS) follows routes.json.
import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const top = join(here, '..', '..')
const workflowsDir = join(top, 'workflows')
const routes = JSON.parse(readFileSync(join(top, 'routes.json'), 'utf8'))
const helperSource = readFileSync(join(top, 'gkh', 'templates', 'routes-helper.js'), 'utf8')

const BEGIN = /^\/\/ <gk-routes v2> generated by gkh gen from routes\.json v(\d+); do not edit$/
const END = '// </gk-routes>'
const PROJECT_END = 'gk-project block: END'
const MARKER = '// gk-harness:args-v1\n'

const scripts = () => readdirSync(workflowsDir).filter((f) => /^gk-.*\.js$/.test(f)).sort()
const wfOf = (f) => f.replace(/\.js$/, '')
const stagesOf = (wf) => Object.keys(routes.stages).filter((k) => k.startsWith(`${wf}.`))

// The block's lines, from the begin marker to the end marker inclusive, or null.
function blockOf(src) {
  const lines = src.split('\n')
  const begins = lines.map((l, i) => (BEGIN.test(l) ? i : -1)).filter((i) => i >= 0)
  if (begins.length !== 1) return { count: begins.length }
  const b = begins[0]
  const e = lines.indexOf(END, b)
  return { count: 1, begin: b, end: e, lines, text: lines.slice(b, e + 1).join('\n') }
}

// Evaluates code that defines the routes block's names, with the given ARGS and stubs.
function evalBlock(code, { ARGS = {}, agent = async () => null } = {}) {
  const logs = []
  const log = (m) => { logs.push(String(m)) }
  const fn = new Function('ARGS', 'agent', 'log',
    `${code}\nreturn { ROUTES: typeof ROUTES === 'undefined' ? undefined : ROUTES, routeOf, runStage, routingResult, DIALS }`)
  return { ...fn(ARGS, agent, log), logs }
}

// ---------------- the block in every script ----------------

test('routes block present and current: one block per gk workflow (none in gk-selftest), right after the gk-project END line', () => {
  const files = scripts()
  assert.ok(files.includes('gk-selftest.js'))
  for (const f of files) {
    const wf = wfOf(f)
    const src = readFileSync(join(workflowsDir, f), 'utf8')
    const blk = blockOf(src)
    if (!stagesOf(wf).length) {
      assert.equal(blk.count, 0, `${f}: no routes block (no stages in routes.json)`)
      continue
    }
    assert.equal(blk.count, 1, `${f}: exactly one routes block`)
    assert.ok(blk.end > blk.begin, `${f}: the block is closed`)
    assert.ok(blk.lines[blk.begin - 1].includes(PROJECT_END), `${f}: the block starts on the line after the gk-project END line`)
    assert.equal(Number(BEGIN.exec(blk.lines[blk.begin])[1]), routes.version, `${f}: the block names routes.json's version`)
    assert.ok(blk.text.includes(helperSource.trimEnd()), `${f}: the helper is the template, verbatim`)
    // The block runs on its own, and its data is this workflow's slice of routes.json.
    const { ROUTES } = evalBlock(blk.text)
    assert.equal(ROUTES.version, routes.version)
    assert.deepEqual(Object.keys(ROUTES.stages), stagesOf(wf), `${f}: the block holds this workflow's stages, in order`)
    for (const k of stagesOf(wf)) assert.deepEqual(ROUTES.stages[k], routes.stages[k], `${f}: stage ${k}`)
    for (const [name, t] of Object.entries(ROUTES.tiers)) {
      const r = routes.tiers[name]
      assert.ok(r, `${f}: tier ${name} is in routes.json`)
      assert.deepEqual([t.model, t.effort], [r.model, r.effort], `${f}: tier ${name}`)
      assert.deepEqual(t.cap, [routes.models[r.model].rank, routes.efforts.indexOf(r.effort) + 1], `${f}: tier ${name} capability`)
    }
    // Every tier any of its stages can name is in the block.
    for (const k of stagesOf(wf)) {
      const s = routes.stages[k]
      const named = [s.tier, ...Object.values(s.byClass || {}), ...Object.values(s.when || {}),
        ...(typeof s.noFable === 'object' ? Object.values(s.noFable) : [s.noFable])]
      for (const t of named) if (t && t !== 'byClass' && t !== 'none') assert.ok(ROUTES.tiers[t], `${f}: ${k} names tier ${t}`)
    }
  }
})

test('meta.phases labels: every phase is mapped to a stage in routes.json phases, and a labelled phase names its base tier\'s model', () => {
  for (const f of scripts()) {
    const wf = wfOf(f)
    if (!stagesOf(wf).length) continue
    const src = readFileSync(join(workflowsDir, f), 'utf8')
    const head = src.slice(0, src.indexOf(MARKER))
    const meta = new Function(`return (${head.slice('export const meta = '.length)})`)()
    const map = routes.phases[wf]
    assert.ok(map, `${f}: routes.json phases has an entry`)
    assert.deepEqual(Object.keys(map).sort(), meta.phases.map((p) => p.title).sort(), `${f}: every phase that runs an agent is mapped`)
    for (const p of meta.phases) {
      const s = routes.stages[map[p.title]]
      assert.ok(s && map[p.title].startsWith(`${wf}.`), `${f}: phase ${p.title} maps to a stage of this workflow`)
      if (!('model' in p)) continue
      const base = s.tier === 'byClass' ? s.byClass.judgement : s.tier
      assert.equal(p.model, routes.tiers[base].model, `${f}: phase ${p.title} model label`)
    }
  }
})

test('the marker stays directly after meta, within 16 KB', () => {
  for (const f of scripts()) {
    const src = readFileSync(join(workflowsDir, f), 'utf8')
    const at = src.indexOf(MARKER)
    assert.ok(at > 0 && src.slice(at - 2, at) === '}\n', `${f}: the marker is right after meta`)
    assert.ok(Buffer.byteLength(src.slice(0, at + MARKER.length)) <= 16384, `${f}: the marker is inside the first 16 KB`)
    const blk = blockOf(src)
    if (blk.count) assert.ok(src.indexOf(blk.lines[blk.begin]) > at, `${f}: the routes block is after the marker`)
  }
})

// ---------------- routeOf ----------------

const T = (model, effort, rank, e) => ({ model, effort, cap: [rank, e] })
const FIXTURE = {
  version: 9,
  tiers: {
    'sonnet-medium': T('sonnet', 'medium', 2, 2),
    'opus-medium': T('opus', 'medium', 3, 2),
    'opus-high': T('opus', 'high', 3, 3),
    'opus-xhigh': T('opus', 'xhigh', 3, 4),
    'fable-medium': T('fable', 'medium', 4, 2),
    'fable-high': T('fable', 'high', 4, 3),
  },
  stages: {
    'wf.base': { tier: 'opus-medium' },
    'wf.implement': {
      tier: 'byClass',
      byClass: { spec: 'sonnet-medium', judgement: 'opus-medium', hard: 'fable-medium', security: 'fable-medium' },
      noFable: { hard: 'opus-high', security: 'opus-high' },
      onFail: 'unfinished',
    },
    'wf.propose': { tier: 'opus-high', when: { ui: 'fable-medium' }, noFable: 'opus-high', onFail: 'rerun' },
    'wf.review': { tier: 'opus-high', atLeast: 'implementer', noFable: 'opus-xhigh', onFail: 'rerun' },
    'wf.judge': { tier: 'opus-high', when: { sensitive: 'fable-high' }, authorFloor: true, noFable: 'opus-xhigh', onFail: 'rerun', apex: true },
    'wf.plan': { tier: 'fable-medium', noFable: 'opus-xhigh', onFail: 'rerun', apex: true },
    'wf.critic': { tier: 'opus-high', apex: true },
    'wf.sign-off': { tier: 'fable-high', noFable: 'none', onFail: 'hold' },
  },
}
const withRoutes = (code) => `const ROUTES = ${JSON.stringify(FIXTURE)}\n${code}`
const helper = (dials, agent) => evalBlock(withRoutes(helperSource), { ARGS: dials === undefined ? {} : { dials }, agent })
const tierOf = (r) => [r.tier, r.model, r.effort, r.off]

test('routeOf rule 1: the base tier, or the byClass tier for ctx.cls (judgement when none)', () => {
  const { routeOf } = helper()
  assert.deepEqual(tierOf(routeOf('wf.base', {})), ['opus-medium', 'opus', 'medium', null])
  assert.deepEqual(tierOf(routeOf('wf.implement', { cls: 'spec' })), ['sonnet-medium', 'sonnet', 'medium', null])
  assert.deepEqual(tierOf(routeOf('wf.implement', {})), ['opus-medium', 'opus', 'medium', null])
  assert.deepEqual(tierOf(routeOf('wf.implement', { cls: 'hard' })), ['fable-medium', 'fable', 'medium', null])
  assert.throws(() => routeOf('wf.nope', {}), /wf\.nope/)
})

test('routeOf rule 2: a when condition whose ctx flag is true sets the tier', () => {
  const { routeOf } = helper()
  assert.equal(routeOf('wf.propose', { ui: true }).tier, 'fable-medium')
  assert.equal(routeOf('wf.propose', { ui: false }).tier, 'opus-high')
  assert.equal(routeOf('wf.judge', { sensitive: true }).tier, 'fable-high')
  assert.equal(routeOf('wf.judge', { ui: true }).tier, 'opus-high')
})

test('routeOf rule 3: atLeast lifts to the highest of the tier, ctx.implementer and opus-high', () => {
  const { routeOf } = helper()
  assert.equal(routeOf('wf.review', {}).tier, 'opus-high')
  assert.equal(routeOf('wf.review', { implementer: 'sonnet-medium' }).tier, 'opus-high')
  assert.equal(routeOf('wf.review', { implementer: 'fable-medium' }).tier, 'fable-medium')
  // atLeast does nothing on a stage without it.
  assert.equal(routeOf('wf.base', { implementer: 'fable-medium' }).tier, 'opus-medium')
})

test('routeOf ruling R4: a hard piece\'s review under nofable is fable-medium by rule 3, then the stage\'s noFable by rule 6', () => {
  const { routeOf } = helper(['nofable'])
  // The caller passes the piece's class tier before any dial (fable-medium, not opus-high).
  assert.deepEqual(tierOf(routeOf('wf.review', { implementer: 'fable-medium' })), ['opus-xhigh', 'opus', 'xhigh', 'nofable'])
})

test('routeOf rule 4: authorFloor lifts to an author above opus-high', () => {
  const { routeOf } = helper()
  assert.equal(routeOf('wf.judge', { author: 'fable-medium' }).tier, 'fable-medium')
  assert.equal(routeOf('wf.judge', { author: 'opus-xhigh' }).tier, 'opus-xhigh')
  assert.equal(routeOf('wf.judge', { author: 'opus-medium' }).tier, 'opus-high')
  assert.equal(routeOf('wf.judge', { sensitive: true, author: 'fable-medium' }).tier, 'fable-high')
  assert.equal(routeOf('wf.propose', { author: 'fable-high' }).tier, 'opus-high')
})

test('routeOf rule 5: the fable dial puts an apex stage on fable-high', () => {
  const { routeOf } = helper(['fable'])
  assert.deepEqual(tierOf(routeOf('wf.judge', {})), ['fable-high', 'fable', 'high', null])
  assert.equal(routeOf('wf.critic', {}).tier, 'fable-high')
  assert.equal(routeOf('wf.review', {}).tier, 'opus-high')
})

test('routeOf rule 6: the nofable dial moves a Fable tier to its noFable tier (per class, or none); nofable wins over fable', () => {
  const { routeOf } = helper(['nofable'])
  assert.deepEqual(tierOf(routeOf('wf.plan', {})), ['opus-xhigh', 'opus', 'xhigh', 'nofable'])
  assert.deepEqual(tierOf(routeOf('wf.implement', { cls: 'hard' })), ['opus-high', 'opus', 'high', 'nofable'])
  assert.deepEqual(tierOf(routeOf('wf.implement', { cls: 'spec' })), ['sonnet-medium', 'sonnet', 'medium', null])
  assert.deepEqual(tierOf(routeOf('wf.propose', { ui: true })), ['opus-high', 'opus', 'high', 'nofable'])
  assert.deepEqual(tierOf(routeOf('wf.propose', {})), ['opus-high', 'opus', 'high', null])
  assert.deepEqual(tierOf(routeOf('wf.sign-off', {})), [null, null, null, 'nofable'])
  const both = helper(['fable', 'nofable']).routeOf
  assert.deepEqual(tierOf(both('wf.judge', {})), ['opus-xhigh', 'opus', 'xhigh', 'nofable'])
  assert.deepEqual(tierOf(both('wf.critic', {})), ['opus-high', 'opus', 'high', null])
})

test('DIALS: only fable, nofable, deep and solo are kept; anything else is logged and dropped', () => {
  const ok = helper(['fable', 'deep', 'solo', 'nofable'])
  assert.deepEqual(ok.DIALS, ['fable', 'deep', 'solo', 'nofable'])
  assert.deepEqual(ok.logs, [])
  const odd = helper(['nofable', 'turbo', 7])
  assert.deepEqual(odd.DIALS, ['nofable'])
  assert.equal(odd.logs.length, 2)
  assert.match(odd.logs[0], /turbo/)
  const notList = helper('nofable')
  assert.deepEqual(notList.DIALS, [])
  assert.equal(notList.logs.length, 1)
  assert.deepEqual(helper().DIALS, [])
  assert.deepEqual(helper().logs, [])
  // ARGS that is not an object (a JSON string the script could not parse) has no dials.
  assert.deepEqual(evalBlock(withRoutes(helperSource), { ARGS: 'not json' }).DIALS, [])
})

// ---------------- runStage ----------------

// An agent stub that records (model, effort, label) and answers from a list, in order.
function recorder(replies) {
  const calls = []
  const agent = async (prompt, opts) => {
    calls.push({ prompt, label: opts.label, model: opts.model, effort: opts.effort, schema: opts.schema })
    return replies.length ? replies.shift() : { ok: true }
  }
  return { calls, agent }
}

test('runStage: calls agent with the route\'s model and effort, keeping the caller\'s opts', async () => {
  const { calls, agent } = recorder([{ ok: 1 }])
  const h = helper(undefined, agent)
  const out = await h.runStage('wf.base', {}, 'p', { label: 'base', schema: { type: 'object', properties: {} } })
  assert.deepEqual(out, { ok: 1 })
  assert.deepEqual(calls.map((c) => [c.label, c.model, c.effort]), [['base', 'opus', 'medium']])
  assert.ok(calls[0].schema)
  assert.deepEqual(h.routingResult(), { routes: 9, dials: [], offTier: [] })
})

test('runStage: a dead Fable stage with onFail rerun runs once more on its noFable tier and records the drop', async () => {
  const { calls, agent } = recorder([null, { verdict: 'ok' }])
  const h = helper(undefined, agent)
  const out = await h.runStage('wf.plan', {}, 'p', { label: 'plan-check' })
  assert.deepEqual(out, { verdict: 'ok' })
  assert.deepEqual(calls.map((c) => [c.label, c.model, c.effort]), [['plan-check', 'fable', 'medium'], ['plan-check', 'opus', 'xhigh']])
  assert.deepEqual(h.routingResult().offTier, [{ stage: 'wf.plan', label: 'plan-check', tier: 'opus-xhigh', reason: 'onFail' }])
})

test('runStage: a dead stage that is not on Fable is not re-run', async () => {
  const { calls, agent } = recorder([null])
  const h = helper(undefined, agent)
  assert.equal(await h.runStage('wf.propose', {}, 'p', { label: 'propose' }), null)
  assert.equal(calls.length, 1)
  assert.deepEqual(h.routingResult().offTier, [])
})

test('runStage: onFail unfinished returns null with no re-run', async () => {
  const { calls, agent } = recorder([null])
  const h = helper(undefined, agent)
  assert.equal(await h.runStage('wf.implement', { cls: 'hard' }, 'p', { label: 'impl:a' }), null)
  assert.deepEqual(calls.map((c) => [c.model, c.effort]), [['fable', 'medium']])
  assert.deepEqual(h.routingResult().offTier, [])
})

test('runStage: onFail hold returns null with no re-run and records the hold', async () => {
  const { calls, agent } = recorder([null])
  const h = helper(undefined, agent)
  assert.equal(await h.runStage('wf.sign-off', {}, 'p', { label: 'sign-off' }), null)
  assert.equal(calls.length, 1)
  assert.deepEqual(h.routingResult().offTier, [{ stage: 'wf.sign-off', label: 'sign-off', tier: 'fable-high', reason: 'hold' }])
})

test('runStage: under nofable a stage whose noFable is none does not run, and is recorded', async () => {
  const { calls, agent } = recorder([])
  const h = helper(['nofable'], agent)
  assert.equal(await h.runStage('wf.sign-off', {}, 'p', { label: 'sign-off' }), null)
  assert.equal(calls.length, 0)
  assert.deepEqual(h.routingResult(), {
    routes: 9,
    dials: ['nofable'],
    offTier: [{ stage: 'wf.sign-off', label: 'sign-off', tier: null, reason: 'nofable' }],
  })
})

test('runStage: under nofable a Fable stage runs on its noFable tier and is recorded', async () => {
  const { calls, agent } = recorder([{ ok: 1 }])
  const h = helper(['nofable'], agent)
  assert.deepEqual(await h.runStage('wf.review', { implementer: 'fable-medium' }, 'p', { label: 'review:a' }), { ok: 1 })
  assert.deepEqual(calls.map((c) => [c.model, c.effort]), [['opus', 'xhigh']])
  assert.deepEqual(h.routingResult().offTier, [{ stage: 'wf.review', label: 'review:a', tier: 'opus-xhigh', reason: 'nofable' }])
})
