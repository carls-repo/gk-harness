const here = dirname(fileURLToPath(import.meta.url))
const top = join(here, '..', '..')
const workflowsDir = join(top, 'workflows')
const routes = JSON.parse(readFileSync(join(top, 'routes.json'), 'utf8'))
const helperSource = readFileSync(join(top, 'gkh', 'templates', 'routes-helper.js'), 'utf8')

const BEGIN = /^\/\/ <gk-routes v2> generated by gkh gen from routes\.json v(\d+); do not edit$/
const END = '// </gk-routes>'
const PROJECT_END = 'gk-project block: END'
// The args marker: v1, or v2 once the script takes its stages from the routes block (Task 9 on).
const MARKER_RE = /^\/\/ gk-harness:args-v[12]\n/m
const markerAt = (src) => { const m = MARKER_RE.exec(src); return m ? { at: m.index, length: m[0].length } : { at: -1, length: 0 } }

const scripts = () => readdirSync(workflowsDir).filter((f) => /^gk-.*\.js$/.test(f)).sort()
const wfOf = (f) => f.replace(/\.js$/, '')
const stagesOf = (wf) => Object.keys(routes.stages).filter((k) => k.startsWith(`${wf}.`))

// The block's lines, from the begin marker to the end marker inclusive, or null.
function blockOf(src) {
  const lines = src.split('\n')
  const begins = lines.map((l, i) => (BEGIN.test(l) ? i : -1)).filter((i) => i >= 0)
  if (begins.length !== 1) return { count: begins.length }
  const b = begins[0]
  const e = lines.indexOf(END, b)
  return { count: 1, begin: b, end: e, lines, text: lines.slice(b, e + 1).join('\n') }
}

// Evaluates code that defines the routes block's names, with the given ARGS and stubs.
function evalBlock(code, { ARGS = {}, agent = async () => null } = {}) {
  const logs = []
  const log = (m) => { logs.push(String(m)) }
  const fn = new Function('ARGS', 'agent', 'log',
    `${code}\nreturn { ROUTES: typeof ROUTES === 'undefined' ? undefined : ROUTES, routeOf, runStage, routingResult, DIALS }`)
  return { ...fn(ARGS, agent, log), logs }
}

